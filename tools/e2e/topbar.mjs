// 學生端上方導覽列：左上「搜尋」（首頁、我的成績）或「回首頁」（單元內頁），B5 在右上；分頁列的我的成績是學生頭像：node tools/e2e/topbar.mjs
import { startWorld, sleep } from './harness.mjs';
const world = await startWorld({ scriptLatency: 40 });
const g = world.gas;
const mk = (id, title, type, lesson) => ({ id, title, type, lesson, topic: '', visible: true, disabled: [], questionCount: 4, custom: true });
g.api('saveAllSettings', [[], [mk('l1-voc', 'L1 單字', 'vocab', 1), mk('l2-voc', 'L2 單字', 'vocab', 2), mk('l3-voc', 'L3 單字', 'vocab', 3)]]);
const words = ['apple', 'banana', 'cherry', 'dates', 'egg', 'fig'].map((w) => ({ word: w, pos: 'n.', zh: '字' + w, example: `I [${w}] it.`, exampleZh: '我。' }));
['l1-voc', 'l2-voc', 'l3-voc'].forEach((id, i) => g.api('saveContent', [id, { topic: ['Food', 'Travel', 'Music'][i], words }, true]));
const ctx = await world.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true, deviceScaleFactor: 2 });
const p = await world.newPage(ctx, { student: true });
import assert from 'node:assert';
const errs = []; p.on('pageerror', (e) => errs.push(e.message));
await p.goto(world.base + '/'); await p.waitForSelector('.unit-tile'); await sleep(800);
const pos = await p.evaluate(() => ({ s: document.querySelector('[data-search]').getBoundingClientRect().left, b: document.querySelector('.brand').getBoundingClientRect().right, w: innerWidth }));
assert.ok(pos.s < 40 && pos.b > pos.w - 40, '搜尋在左上、B5 在右上 ' + JSON.stringify(pos));
assert.equal(await p.textContent('#dock a[data-dock="account"] .dock-av'), '陳', '分頁列第三格是帳號（學生頭像）');
assert.equal(await p.$$eval('#dock a', (a) => a.map((x) => x.dataset.dock).join()), 'home,me,account');
await p.tap('[data-search]'); await sleep(400);
await p.fill('dialog.search-sheet input', 'l2');
await sleep(300);
assert.deepEqual(await p.$$eval('.ss-row', (a) => a.map((x) => x.getAttribute('href'))), ['#/u/l2-voc']);
await p.fill('dialog.search-sheet input', 'music');
assert.deepEqual(await p.$$eval('.ss-row', (a) => a.map((x) => x.getAttribute('href'))), ['#/u/l3-voc'], '可用主題搜尋');
await p.fill('dialog.search-sheet input', 'zzz');
assert.match(await p.textContent('.ss-empty'), /找不到/);
await p.fill('dialog.search-sheet input', '');
await sleep(200);
await p.fill('dialog.search-sheet input', 'l3');
await p.tap('.ss-row'); await sleep(900);
assert.equal(await p.evaluate(() => location.hash), '#/u/l3-voc'); assert.equal(await p.$$eval('dialog.search-sheet', (a) => a.length), 0);
assert.equal(await p.$$eval('[data-search]', (a) => a.length), 0, '單元內頁：左上是回首頁');
await p.tap('.top-back'); await sleep(800);
assert.ok(await p.$('.unit-tile'), '回首頁');
await p.tap('#dock a[data-dock="me"]'); await sleep(800);
assert.ok(await p.$('.me-row') && !(await p.$('.me-acct')) && await p.$('[data-search]'), '我的成績：只有成績，左上是搜尋');
await p.tap('#dock a[data-dock="account"]'); await p.waitForSelector('.acct-head'); await sleep(700);
const ink = await p.evaluate(() => { const i = document.querySelector('.dock-ink').getBoundingClientRect(), c = document.querySelector('#dock a[aria-current]').getBoundingClientRect(); return Math.abs(i.left - c.left) + Math.abs(i.width - c.width); });
assert.ok(ink < 2, '膠囊對齊帳號分頁 ' + ink);
assert.ok(await p.$('.me-acct [data-switch]') && await p.$('.me-acct [data-logout]') && await p.$('[data-search]'), '帳號頁：切換學生、登出；左上是搜尋');
// 帳號頁的學習設定：句型說明的看法、自動下一題，按了就存
await p.tap('[data-learn="read"]'); await sleep(200);
assert.equal(await p.getAttribute('[data-learn="read"]', 'aria-checked'), 'true');
assert.equal(await p.evaluate(() => JSON.parse(localStorage.getItem('b5p:learnPrefs')).mode), 'read', '句型說明的看法存起來（句型練習會照這個設定）');
const a0 = await p.getAttribute('[data-auto]', 'aria-checked');
await p.tap('[data-auto]'); await sleep(200);
assert.notEqual(await p.getAttribute('[data-auto]', 'aria-checked'), a0);
assert.equal(await p.evaluate(() => localStorage.getItem('b5p:auto')), a0 === 'true' ? '0' : '1');
assert.match(await p.textContent('.set-saved'), /已儲存/);
assert.deepEqual(errs, []);
console.log('上方導覽列測試通過');
await world.close?.(); process.exit(0);
