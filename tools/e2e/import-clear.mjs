// 匯入輸入框的一鍵清空（手機）：有內容才出現「清空」，按了清空、可以「復原」；網站上已儲存的題目不受影響：node tools/e2e/import-clear.mjs
import assert from 'node:assert';
import { startWorld, sleep } from './harness.mjs';
const world = await startWorld({ scriptLatency: 40 });
const g = world.gas;
g.api('saveAllSettings', [[], [{ id: 'u1', title: 'L1 單字', type: 'vocab', lesson: 1, topic: '', visible: true, disabled: [], questionCount: 4, custom: true }]]);
const ctx = await world.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true });
const t = await world.newPage(ctx, { staff: 'teacher@example.com' });
const errs = []; t.on('pageerror', (e) => errs.push(e.message));
await t.goto(world.base + '/admin.html#unit/u1/content'); await sleep(2500);
await t.getByRole('button', { name: /貼上文字/ }).first().tap(); await sleep(800);
const btn = '[data-clear="v-text"]';
assert.equal(await t.isVisible(btn), false, '空的時候不顯示清空');
await t.fill('#v-text', 'apple | n. | 蘋果 | I eat an [apple]. | 我吃蘋果。\nbad line');
await sleep(200);
assert.equal(await t.isVisible(btn), true, '有內容時出現清空');
await t.tap('#imp-check'); await sleep(400);
assert.ok((await t.innerHTML('#imp-report')).length > 0);
const box = await t.locator(btn).boundingBox();
assert.ok(box.height >= 34 && box.x + box.width <= 390, '手機上按得到 ' + JSON.stringify(box));
await t.tap(btn); await sleep(200);
assert.equal(await t.inputValue('#v-text'), '', '一鍵清空');
assert.equal(await t.innerHTML('#imp-report'), '', '檢查結果一起清掉');
assert.match(await t.textContent(btn), /復原/);
await t.tap(btn); await sleep(200);
assert.match(await t.inputValue('#v-text'), /^apple/, '按復原拿回剛剛的內容');
assert.match(await t.textContent(btn), /清空/);
assert.deepEqual(errs, []);
console.log('匯入輸入框一鍵清空測試通過');
await world.close?.(); process.exit(0);
