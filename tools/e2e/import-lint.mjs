// 匯入外部 AI 的內容有錯時：每個問題標出第幾行與那一行的原文，點行號跳到輸入框那一行並選取：node tools/e2e/import-lint.mjs
import assert from 'node:assert';
import { startWorld, sleep } from './harness.mjs';
const world = await startWorld({ scriptLatency: 40 });
const g = world.gas;
g.api('saveAllSettings', [[], [{ id: 'u1', title: 'L1 單字', type: 'vocab', lesson: 1, topic: '', visible: true, disabled: [], questionCount: 4, custom: true }, { id: 'r1', title: 'L1 閱讀', type: 'reading', lesson: 1, topic: '', visible: true, disabled: [], questionCount: 4, custom: true }]]);
const ctx = await world.newContext({ viewport: { width: 1280, height: 900 } });
const t = await world.newPage(ctx, { staff: 'teacher@example.com' });
const errs = []; t.on('pageerror', (e) => errs.push(e.message));
await t.goto(world.base + '/admin.html#unit/u1/content'); await sleep(2500);
await t.getByRole('button', { name: /貼上文字/ }).first().click(); await sleep(800);
const vis = await t.evaluate(() => { const v = document.getElementById('v-text'); return v && v.offsetParent !== null; });
assert.ok(vis);
const lines = ['以下是整理好的單字表：', '', '| 英文 | 詞性 | 中文 | 例句 | 例句中文 |', '|---|---|---|---|---|'];
const ok = ['apple', 'banana', 'cherry', 'grape', 'lemon', 'mango', 'peach'];
ok.forEach((w, i) => lines.push(`| ${w} | n. | 水果${i} | I like the [${w}]. | 我喜歡。 |`));
lines.splice(8, 0, '| melon | n. | 甜瓜 | I bought a big watermelon yesterday. | 我買了西瓜。 |');
lines.push('| grape | n. | 葡萄 | The [grape] is sweet. | 葡萄很甜。 |');
lines.push('| kiwi n. 奇異果 I eat a kiwi. |');
await t.evaluate((v) => { const ta = document.getElementById('v-text'); ta.value = v; ta.dispatchEvent(new Event('input', { bubbles: true })); }, lines.join('\n'));
await t.click('#imp-check'); await sleep(600);
const items = await t.$$eval('#imp-report .lint li', (a) => a.map((li) => li.innerText.replace(/\s+/g, ' ')));
console.log('   ', items.join('\n    '));
assert.equal(items.length, 4, '三個錯誤＋一則略過說明文字的提醒');
assert.match(items[0], /^第 9 行 「melon」：例句裡找不到這個字.*watermelon/);
assert.match(items[1], /^第 13 行 「grape」：和第 8 行重複/);
assert.match(items[2], /^第 14 行 這一行讀不出欄位.*kiwi/);
assert.match(items[3], /^第 1 行 看起來是說明文字/);
await t.click('#imp-report .lint li:first-child .jump'); await sleep(900);
const sel = await t.evaluate(() => { const ta = document.getElementById('v-text'); return { focus: document.activeElement === ta, sel: ta.value.slice(ta.selectionStart, ta.selectionEnd) }; });
assert.ok(sel.focus); assert.match(sel.sel, /^\| melon \|.*我買了西瓜。 \|$/, '點「第 9 行」選取輸入框的第 9 行');
// 課文理解批次貼上：答案寫錯、沒有依據，標出是哪一行
await t.goto(world.base + '/admin.html#unit/r1/content'); await sleep(1500);
await t.getByRole('button', { name: /貼上文字/ }).first().click(); await sleep(600);
await t.evaluate(() => { const d = document.getElementById('r-bulk').closest('details'); if (d) d.open = true; });
await t.fill('#r-bulk', ['標題：Tea', '文章：Tea is a drink made from leaves.', '', 'Q1：What is tea made from?', 'Q1選項：Leaves | Rocks | Milk | Sand', 'Q1答案：E', 'Q1依據：made from leaves'].join('\n'));
await t.click('#r-bulk-go'); await sleep(500);
const rb = await t.$$eval('#r-bulk-lint .lint li', (a) => a.map((li) => li.innerText.replace(/\s+/g, ' ')));
console.log('   ', rb.join('\n    '));
assert.ok(rb.some((x) => /^第 6 行 第 1 題的答案要寫 A–D（目前是「E」）/.test(x)), '課文理解：答案錯在第 6 行');
assert.deepEqual(errs, []);
console.log('匯入錯誤標示測試通過');
await world.close?.(); process.exit(0);
